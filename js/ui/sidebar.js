  /* ══ Yıldız butonunu güncelle + favbar'i aç/kapat ══ */
  function _renderFavBar() {
    // --- Favbar görünürlüğü ---
    if (!_favBarEl) return;
    const show = _showFavBar && _favorites.length > 0;
    _favBarEl.style.display = show ? 'flex' : 'none';

    // --- Spacer + chart resize: favbar açıksa zaman cetveli yukarı kayar ---
    const pane0 = document.getElementById('pane-0');
    if (pane0) pane0.classList.toggle('favbar-open', show);
    const spacer = document.getElementById('favbar-spacer');
    if (spacer) spacer.style.height = show ? '40px' : '0';
    // CSS transition (150ms) bittikten sonra chart'ı resize et
    setTimeout(() => { try { ChartCore.resize(); } catch(e){} }, 160);

    // --- İçerik ---
    if (show) {
      const html = _favorites.map((fId, idx) => {
        const tool = ALL_TOOLS[fId]; if (!tool) return '';
        return `<button class="favorites-bar__item${_activeTool === fId ? ' active' : ''}" draggable="true"
          data-action="favtool" data-tool="${fId}" data-idx="${idx}" title="${tool.label}">${TI[tool.icon] || ''}</button>`;
      }).join('');
      _favBarEl.innerHTML = html;
      _favBarEl.querySelectorAll('[data-action="favtool"]').forEach(btn => {
        btn.addEventListener('click', () => _setActiveTool(btn.dataset.tool));
        btn.addEventListener('dragstart', e => { _dragIdx = +btn.dataset.idx; e.dataTransfer.effectAllowed = 'move'; });
        btn.addEventListener('dragover', e => {
          e.preventDefault();
          const idx = +btn.dataset.idx;
          if (_dragIdx == null || _dragIdx === idx) return;
          const next = [..._favorites]; const [m] = next.splice(_dragIdx, 1); next.splice(idx, 0, m);
          _favorites = next; _saveFavorites(); _dragIdx = idx; _renderFavBar();
        });
        btn.addEventListener('dragend', () => { _dragIdx = null; });
      });
    }

    // --- Yıldız buton görünümü ---
    const starBtn = document.getElementById('fav-toggle-btn');
    if (starBtn) {
      starBtn.classList.toggle('active', show);
      const svg = starBtn.querySelector('svg');
      if (svg) {
        svg.setAttribute('fill', show ? '#f59e0b' : 'none');
        svg.setAttribute('stroke', show ? '#f59e0b' : 'currentColor');
      }
    }
  }

